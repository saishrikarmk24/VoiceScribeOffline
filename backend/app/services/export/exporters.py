def export_pdf(payload: dict[str, Any]) -> bytes:
    """Render the encounter to a PDF matching SIMS Hospital Ambulatory Care Clinical Notes."""
    from pathlib import Path
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        HRFlowable,
        Image,
        KeepTogether,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    session = payload.get("session", {})
    note = payload.get("clinical_note", {})
    content = note.get("content", {})
    entities: list[dict[str, Any]] = payload.get("clinical_entities", [])
    segments: list[dict[str, Any]] = payload.get("transcript", [])

    # Date formatting
    started_at = session.get("started_at") or session.get("created_at")
    appt_date = _format_display_date(started_at)
    print_date = datetime.now(timezone.utc).strftime("%b %d, %Y")

    # Demographic & encounter details
    hh_no = str(session.get("patient_id") or session.get("reference") or "HH-6838").strip()
    explicit_patient_name = session.get("patient_name")
    if explicit_patient_name and str(explicit_patient_name).strip():
        patient_name = str(explicit_patient_name).strip()
    else:
        raw_name = str(session.get("name") or "").strip()
        lower_raw = raw_name.lower()
        if (
            not raw_name
            or lower_raw.startswith("outpatient")
            or lower_raw.startswith("inpatient")
            or lower_raw.startswith("google meet")
            or lower_raw.startswith("telehealth")
            or lower_raw.startswith("sim-pt")
            or "consultation" in lower_raw
            or "meeting" in lower_raw
        ):
            patient_name = str(session.get("patient_id") or "Patient").strip()
        else:
            patient_name = raw_name

    gender = session.get("patient_gender") or session.get("gender") or "Male"
    age = session.get("patient_age") or session.get("age") or "48 Yrs"
    consult_name = session.get("doctor_name") or "Sims Hospital"
    speciality = session.get("speciality") or "Doctor"

    styles = getSampleStyleSheet()
    navy_dark = colors.HexColor("#1e3a8a")
    navy_header = colors.HexColor("#0f2942")
    slate_dark = colors.HexColor("#1e293b")
    text_muted = colors.HexColor("#64748b")
    bullet_pink = colors.HexColor("#e11d48")

    doc_title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10.5,
        leading=13,
        textColor=navy_header,
        alignment=TA_CENTER,
        spaceBefore=4,
        spaceAfter=8,
    )
    meta_label_style = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=11,
        textColor=slate_dark,
    )
    meta_val_style = ParagraphStyle(
        "MetaVal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=slate_dark,
    )
    sec_heading_style = ParagraphStyle(
        "SecHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=slate_dark,
        spaceBefore=4,
        spaceAfter=2,
    )
    sec_body_style = ParagraphStyle(
        "SecBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#334155"),
        spaceAfter=4,
    )
    table_header_style = ParagraphStyle(
        "THeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7.8,
        leading=10,
        textColor=slate_dark,
    )
    table_cell_style = ParagraphStyle(
        "TCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7.6,
        leading=10,
        textColor=colors.HexColor("#475569"),
    )
    footer_style = ParagraphStyle(
        "FooterText",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7.2,
        leading=9,
        textColor=text_muted,
    )

    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=10 * mm,
        bottomMargin=12 * mm,
        title=f"SIMS Hospital - {hh_no}",
        author="SIMS Hospital Chennai",
    )

    story: list[Any] = []

    # 1. Header with SIMS Hospital Logo or Styled Navy Banner
    logo_path = Path(__file__).resolve().parent.parent.parent / "assets" / "sims_logo.png"
    if logo_path.exists():
        try:
            story.append(Image(str(logo_path), width=54 * mm, height=18 * mm))
            story.append(Spacer(1, 2 * mm))
        except Exception:
            pass
    else:
        # Styled Navy Header Bar fallback
        header_table = Table(
            [[Paragraph("<font color='white'><b>SIMS HOSPITAL</b><br/><font size='7.5'>CHENNAI</font></font>", ParagraphStyle("Hdr", alignment=TA_CENTER))]],
            colWidths=[182 * mm],
        )
        header_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#1e3a8a")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ])
        )
        story.append(header_table)
        story.append(Spacer(1, 2 * mm))

    story.append(Paragraph("AMBULATORY CARE - CLINICAL NOTES", doc_title_style))

    # 2. Patient & Encounter Metadata Grid (2-column layout matching reference PDF)
    meta_data = [
        [
            Paragraph("Appointment Date & Time", meta_label_style),
            Paragraph(f": {appt_date}", meta_val_style),
            Paragraph("Print Date Time", meta_label_style),
            Paragraph(f": {print_date}", meta_val_style),
        ],
        [
            Paragraph("HH No.", meta_label_style),
            Paragraph(f": {hh_no}", meta_val_style),
            Paragraph("Patient Name", meta_label_style),
            Paragraph(f": {patient_name}", meta_val_style),
        ],
        [
            Paragraph("Gender", meta_label_style),
            Paragraph(f": {gender}", meta_val_style),
            Paragraph("Age", meta_label_style),
            Paragraph(f": {age}", meta_val_style),
        ],
        [
            Paragraph("Consult Name", meta_label_style),
            Paragraph(f": {consult_name}", meta_val_style),
            Paragraph("Speciality", meta_label_style),
            Paragraph(f": {speciality}", meta_val_style),
        ],
    ]

    meta_table = Table(meta_data, colWidths=[42 * mm, 49 * mm, 38 * mm, 53 * mm])
    meta_table.setStyle(
        TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 1.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ])
    )
    story.append(meta_table)
    story.append(Spacer(1, 3.5 * mm))

    # 3. The 13 Standard Ambulatory Care Sections
    AMBULATORY_SECTIONS = [
        ("Presenting Complaint", ["chief_complaint"]),
        ("History of Present Illness", ["history_of_present_illness"]),
        ("Past History", ["relevant_medical_history", "past_history"]),
        ("Social History", ["social_history"]),
        ("Family History", ["family_history"]),
        ("Menstrual History", ["menstrual_history"]),
        ("Physical Examination", ["physical_examination", "examination", "vitals"]),
        ("Current Medication", ["current_medication"]),
        ("Allergies", ["allergies"]),
        ("Treatment History", ["treatment_history"]),
        ("Previous Investigation", ["previous_investigation"]),
        ("Assessment and Plan", ["assessment"]),
        ("Plan Of Care", ["plan", "follow_up"]),
    ]

    # Pre-extract entities for quick section synthesis if not present in note content
    med_entities = [e.get("value") for e in entities if str(e.get("entity_type")).upper() == "MEDICATION" and e.get("value")]
    allergy_entities = [e.get("value") for e in entities if str(e.get("entity_type")).upper() == "ALLERGY" and e.get("value")]
    inv_entities = [e.get("value") for e in entities if str(e.get("entity_type")).upper() in ("INVESTIGATION", "PROCEDURE") and e.get("value")]

    for label, keys in AMBULATORY_SECTIONS:
        text = ""
        for key in keys:
            sec = content.get(key) or {}
            val = str(sec.get("text") or "").strip()
            if val and val.lower() not in _UNDOCUMENTED_PHRASES:
                text = f"{text} {val}".strip() if text else val

        if not text:
            if label == "Current Medication" and med_entities:
                text = ", ".join(med_entities)
            elif label == "Allergies" and allergy_entities:
                text = ", ".join(allergy_entities)
            elif label == "Previous Investigation" and inv_entities:
                text = ", ".join(inv_entities)
            else:
                text = "---"

        # Pink circular badge icon with bold section heading
        sec_header_text = f"<font color='#e11d48' size='9'>&#9679;</font> &nbsp;<b>{label}</b>"
        story.append(Paragraph(sec_header_text, sec_heading_style))
        story.append(Paragraph(text, sec_body_style))

    story.append(Spacer(1, 2 * mm))

    # 4. Prescription Table
    story.append(Paragraph("<b>Prescription</b>", sec_heading_style))
    rx_rows = [[
        Paragraph("Date", table_header_style),
        Paragraph("Drug Names", table_header_style),
        Paragraph("Dosage", table_header_style),
        Paragraph("Frequency/Mode", table_header_style),
        Paragraph("Route", table_header_style),
        Paragraph("Duration", table_header_style),
    ]]

    rx_prescriptions = _extract_doctor_prescriptions(content, entities, segments, appt_date)
