class FHIRAdapter:
    """Maps a MedScribe session onto a FHIR-compatible R4 bundle."""

    OBSERVATION_TYPES = {
        EntityType.SYMPTOM,
        EntityType.FINDING,
        EntityType.SEVERITY,
        EntityType.FREQUENCY,
        EntityType.DURATION,
        EntityType.CHARACTER,
    }

    def build_bundle(
        self,
        *,
        session: dict[str, Any],
        note: dict[str, Any],
        entities: list[dict[str, Any]],
        segments: list[dict[str, Any]],
    ) -> dict[str, Any]:
        patient_id = f"patient-{_slug(session.get('patient_id', 'sim'))}"
        encounter_id = f"encounter-{_slug(session.get('reference', 'sim'))}"
        recorded = note.get("updated_at") or datetime.now(timezone.utc).isoformat()

        resources: list[dict[str, Any]] = [
            self._patient(patient_id, session),
            self._encounter(encounter_id, patient_id, session),
        ]

        for entity in entities:
            entity_type = _as_entity_type(entity.get("entity_type"))
            if entity_type is None:
                continue
            if entity_type in self.OBSERVATION_TYPES:
                resources.append(self._observation(entity, patient_id, encounter_id, recorded))
            elif entity_type is EntityType.MEDICATION:
                resources.append(self._medication_statement(entity, patient_id, encounter_id, recorded))
            elif entity_type is EntityType.ALLERGY:
                resources.append(self._allergy(entity, patient_id, recorded))
            elif entity_type is EntityType.INVESTIGATION:
                resources.append(self._service_request(entity, patient_id, encounter_id, recorded))
            elif entity_type in (EntityType.PLAN, EntityType.FOLLOW_UP):
                resources.append(self._care_plan(entity, patient_id, encounter_id, recorded))

        resources.append(self._diagnostic_report(note, patient_id, encounter_id, recorded, len(segments)))

        return {
            "resourceType": "Bundle",
            "id": f"medscribe-{_slug(session.get('reference', 'sim'))}",
            "type": "collection",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "meta": {
                "profile": [],
                "tag": [
                    {"system": "http://medscribe.local/tags", "code": "encounter", "display": "Clinical encounter"},
                    {
                        "system": "http://medscribe.local/tags",
                        "code": "fhir-compatible",
                        "display": f"FHIR {FHIR_VERSION} compatible subset - not conformance validated",
                    },
                ],
            },
            "entry": [{"fullUrl": f"urn:uuid:{uuid.uuid4()}", "resource": resource} for resource in resources],
        }

    # ------------------------------------------------------------- resources
    @staticmethod
    def _patient(patient_id: str, session: dict[str, Any]) -> dict[str, Any]:
        return {
            "resourceType": "Patient",
            "id": patient_id,
            "identifier": [
                {
                    "system": "http://medscribe.local/patient",
                    "value": str(session.get("patient_id", "unknown")),
                }
            ],
            "active": True,
            "name": [{"use": "anonymous", "text": "Patient"}],
        }

    @staticmethod
    def _encounter(encounter_id: str, patient_id: str, session: dict[str, Any]) -> dict[str, Any]:
        return {
            "resourceType": "Encounter",
            "id": encounter_id,
            "status": "finished" if session.get("ended_at") else "in-progress",
            "class": {
                "system": "http://terminology.hl7.org/CodeSystem/v3-ActCode",
                "code": "AMB",
                "display": "ambulatory",
            },
            "subject": {"reference": f"Patient/{patient_id}"},
            "period": {"start": session.get("started_at"), "end": session.get("ended_at")},
            "reasonCode": [{"text": session.get("scenario") or "Clinical encounter"}],
        }

    @staticmethod
    def _observation(
        entity: dict[str, Any], patient_id: str, encounter_id: str, recorded: str
    ) -> dict[str, Any]:
        status = str(entity.get("status", "UNKNOWN"))
        resource = {
            "resourceType": "Observation",
            "id": f"observation-{_slug(entity.get('ref', uuid.uuid4().hex))}",
            "status": "preliminary",
            "category": [
                {
                    "coding": [
                        {
                            "system": "http://terminology.hl7.org/CodeSystem/observation-category",
                            "code": "exam",
                        }
                    ]
                }
            ],
            "code": _codeable(entity),
            "subject": {"reference": f"Patient/{patient_id}"},
            "encounter": {"reference": f"Encounter/{encounter_id}"},
            "effectiveDateTime": recorded,
            "note": [{"text": _provenance_text(entity)}],
        }
        if status == "NEGATED":
            resource["valueCodeableConcept"] = {
                "coding": [{"system": "http://terminology.hl7.org/CodeSystem/v2-0136", "code": "N"}],
                "text": "Explicitly denied by the speaker",
            }
        elif status == "UNCERTAIN":
            resource["dataAbsentReason"] = {"text": "Uncertain - hedged statement, not confirmed"}
        return resource

    @staticmethod
    def _medication_statement(
        entity: dict[str, Any], patient_id: str, encounter_id: str, recorded: str
    ) -> dict[str, Any]:
        return {
            "resourceType": "MedicationStatement",
            "id": f"medication-{_slug(entity.get('ref', uuid.uuid4().hex))}",
            "status": "recorded" if str(entity.get("status")) != "NEGATED" else "not-taken",
            "medicationCodeableConcept": _codeable(entity),
            "subject": {"reference": f"Patient/{patient_id}"},
            "context": {"reference": f"Encounter/{encounter_id}"},
            "dateAsserted": recorded,
            "note": [{"text": _provenance_text(entity)}],
        }

    @staticmethod
    def _allergy(entity: dict[str, Any], patient_id: str, recorded: str) -> dict[str, Any]:
        negated = str(entity.get("status")) == "NEGATED"
        return {
            "resourceType": "AllergyIntolerance",
            "id": f"allergy-{_slug(entity.get('ref', uuid.uuid4().hex))}",
            "clinicalStatus": {
                "coding": [
                    {
                        "system": "http://terminology.hl7.org/CodeSystem/allergyintolerance-clinical",
                        "code": "inactive" if negated else "active",
                    }
                ]
            },
            "verificationStatus": {
                "coding": [
                    {
                        "system": "http://terminology.hl7.org/CodeSystem/allergyintolerance-verification",
                        "code": "refuted" if negated else "unconfirmed",
                    }
                ]
            },
            "code": _codeable(entity),
            "patient": {"reference": f"Patient/{patient_id}"},
            "recordedDate": recorded,
            "note": [{"text": _provenance_text(entity)}],
        }

    @staticmethod
    def _service_request(
        entity: dict[str, Any], patient_id: str, encounter_id: str, recorded: str
    ) -> dict[str, Any]:
        return {
            "resourceType": "ServiceRequest",
            "id": f"servicerequest-{_slug(entity.get('ref', uuid.uuid4().hex))}",
            "status": "draft",
            "intent": "proposal",
            "code": _codeable(entity),
            "subject": {"reference": f"Patient/{patient_id}"},
            "encounter": {"reference": f"Encounter/{encounter_id}"},
            "authoredOn": recorded,
            "note": [{"text": _provenance_text(entity)}],
        }

    @staticmethod
    def _care_plan(
        entity: dict[str, Any], patient_id: str, encounter_id: str, recorded: str
    ) -> dict[str, Any]:
        return {
            "resourceType": "CarePlan",
            "id": f"careplan-{_slug(entity.get('ref', uuid.uuid4().hex))}",
            "status": "draft",
            "intent": "proposal",
            "title": str(entity.get("entity_type", "PLAN")).replace("_", " ").title(),
            "description": str(entity.get("value", "")),
            "subject": {"reference": f"Patient/{patient_id}"},
            "encounter": {"reference": f"Encounter/{encounter_id}"},
            "created": recorded,
            "note": [{"text": _provenance_text(entity)}],
        }

    @staticmethod
    def _diagnostic_report(
        note: dict[str, Any], patient_id: str, encounter_id: str, recorded: str, segment_count: int
    ) -> dict[str, Any]:
        content = note.get("content", {})
        lines = []
        for key in SECTION_KEYS:
            section = content.get(key) or {}
            if not _section_documented(section):
                continue
            lines.append(f"{SECTION_LABELS[key]}: {section.get('text')}")
        narrative = "<div xmlns=\"http://www.w3.org/1999/xhtml\">" + "".join(
            f"<p>{_escape(line)}</p>" for line in lines
        ) + f"<p><em>{_escape(DISCLAIMER)}</em></p></div>"
        return {
            "resourceType": "DiagnosticReport",
            "id": f"report-{_slug(str(note.get('id', uuid.uuid4().hex)))}",
            "status": "preliminary" if str(note.get("status")) != "APPROVED" else "final",
            "code": {"text": "AI-assisted clinical documentation"},
            "subject": {"reference": f"Patient/{patient_id}"},
            "encounter": {"reference": f"Encounter/{encounter_id}"},
            "issued": recorded,
            "conclusion": (
                (content.get("assessment") or {}).get("text")
                if _section_documented(content.get("assessment"))
                else None
            ),
            "text": {"status": "generated", "div": narrative},
            "extension": [
                {
                    "url": "http://medscribe.local/StructureDefinition/transcript-segment-count",
                    "valueInteger": segment_count,
                },
                {
                    "url": "http://medscribe.local/StructureDefinition/note-version",
                    "valueInteger": int(note.get("version") or 0),
                },
            ],
        }


def _codeable(entity: dict[str, Any]) -> dict[str, Any]:
    """Only emit a coding when a verified code exists - never fabricate one."""
    text = str(entity.get("normalized_value") or entity.get("value") or "")
    code = entity.get("normalized_code")
    system = entity.get("terminology_system")
    if code and system:
        return {"coding": [{"system": _system_url(system), "code": code, "display": text}], "text": text}
    return {"text": text}


def _system_url(system: str) -> str:
    return {
        "SNOMED-CT": "http://snomed.info/sct",
        "ICD-10": "http://hl7.org/fhir/sid/icd-10",
        "RxNorm": "http://www.nlm.nih.gov/research/umls/rxnorm",
        "LOINC": "http://loinc.org",
    }.get(system, f"http://medscribe.local/{_slug(system)}")


def _provenance_text(entity: dict[str, Any]) -> str:
    refs = ", ".join(entity.get("source_segment_refs") or []) or "none"
    return (
        f"Status: {entity.get('status')}. Extraction confidence: "
        f"{float(entity.get('confidence') or 0) * 100:.0f}%. Transcript evidence: {refs}. "
        "Requires human review."
    )


def _as_entity_type(value: Any) -> EntityType | None:
    if isinstance(value, EntityType):
        return value
    try:
        return EntityType(str(value))
    except ValueError:
        return None


def _slug(value: Any) -> str:
    text = str(value).lower()
    return "".join(char if char.isalnum() else "-" for char in text).strip("-") or "unknown"


def _escape(value: str) -> str:
    return (
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def note_status_is_approved(note: dict[str, Any]) -> bool:
    return str(note.get("status")) == "APPROVED"


def entity_status_label(status: Any) -> str:
    try:
        return EntityStatus(str(status)).value
    except ValueError:
        return "UNKNOWN"


